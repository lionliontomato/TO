const colors = ["col-name", "col-diamond", "col-song", "col-bomb", "col-total"];
const metricBgs = {
  "存鑽數量": "#e8f8ff",
  "存歌數量": "#edf2ff",
  "存爆數量": "#fff0f6",
  "總數": "#fff7db"
};

const fmt = new Intl.NumberFormat("zh-Hant-TW");
const $ = (selector) => document.querySelector(selector);

function normalize(text) {
  return String(text ?? "").trim().toLowerCase();
}

function renderSummary() {
  const totals = headers.map((header) => {
    if (header === "存鑽老闆") return { label: "登錄人數", value: records.length, accent: "#bcecff" };
    return {
      label: header,
      value: records.reduce((sum, item) => sum + Number(item[header] || 0), 0),
      accent: metricBgs[header] || "#d9f3ff"
    };
  });

  $("#summaryGrid").innerHTML = totals.map(item => `
    <article class="summary-card" style="--accent:${item.accent}">
      <div class="label">${item.label}</div>
      <div class="value">${fmt.format(item.value)}</div>
    </article>
  `).join("");
}

function renderTable(items) {
  $("#tableHead").innerHTML = `<tr>${headers.map((h, index) => `<th class="${colors[index]}">${h}</th>`).join("")}</tr>`;
  $("#tableBody").innerHTML = items.map(item => `
    <tr>
      ${headers.map((h, index) => {
        const value = index === 0 ? item[h] : fmt.format(item[h]);
        return `<td class="${index === 0 ? 'name-cell' : ''}">${value}</td>`;
      }).join("")}
    </tr>
  `).join("");
}

function renderCards(items) {
  const cardArea = $("#cards");
  if (items.length === 0) {
    cardArea.innerHTML = `<div class="empty-state">查無資料，請確認名字是否與名冊相同。</div>`;
    return;
  }

  const limitedItems = items.length > 12 ? items.slice(0, 12) : items;
  cardArea.innerHTML = limitedItems.map(item => `
    <article class="person-card">
      <div class="person-name"><span>${item[headers[0]]}</span><span>☁️</span></div>
      <div class="metric-grid">
        ${headers.slice(1).map(h => `
          <div class="metric ${h === '總數' ? 'total' : ''}" style="--metric-bg:${metricBgs[h]}">
            <strong>${h}</strong>
            <span>${fmt.format(item[h])}</span>
          </div>
        `).join("")}
      </div>
    </article>
  `).join("");
}

function updateResultText(items, keyword) {
  const text = keyword
    ? `搜尋「${keyword}」：找到 ${items.length} 筆資料。`
    : `目前顯示全部 ${records.length} 筆資料。`;
  $("#resultText").textContent = text;
}

function filterRecords() {
  const keyword = $("#searchInput").value.trim();
  const key = normalize(keyword);
  const items = !key
    ? records
    : records.filter(item => normalize(item[headers[0]]).includes(key));

  renderCards(items);
  renderTable(items);
  updateResultText(items, keyword);
}

function init() {
  renderSummary();
  renderTable(records);
  renderCards(records);
  updateResultText(records, "");

  $("#searchInput").addEventListener("input", filterRecords);
  $("#clearBtn").addEventListener("click", () => {
    $("#searchInput").value = "";
    filterRecords();
    $("#searchInput").focus();
  });
}

document.addEventListener("DOMContentLoaded", init);
